import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import {
  mkdir,
  readFile,
  readdir,
  rm,
  unlink,
  writeFile,
} from "node:fs/promises";
import { resolve } from "node:path";
import { createServer } from "vite";
import { generateElementwiseOpIr } from "./build-elementwise-op-ir.mjs";

const generatedPath = resolve(
  "src/runtime/elementwise-op-declarations.generated.ts",
);
const reportPath = resolve(".typenn-build/fusion-test-results.json");
const generatedBefore = await readFile(generatedPath).catch(() => undefined);
let server;
let report = {
  commit: "unavailable",
  worktreeFingerprint: "unavailable",
  helperFingerprint: "unavailable",
  gpu: "not-run",
  passed: false,
  tests: [],
};

function git(args) {
  return execFileSync("git", args, { encoding: "utf8" }).trim();
}

async function fingerprintWorktree() {
  const hash = createHash("sha256");
  hash.update(git(["diff", "--binary", "HEAD"]));
  const untracked = git(["ls-files", "--others", "--exclude-standard"])
    .split(/\r?\n/)
    .filter(Boolean)
    .sort();
  for (const file of untracked) {
    hash.update("\0");
    hash.update(file);
    hash.update("\0");
    hash.update(await readFile(resolve(file)));
  }
  return hash.digest("hex");
}

async function removeGeneratedShadeViews(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const file = resolve(directory, entry.name);
    if (entry.isDirectory()) await removeGeneratedShadeViews(file);
    else if (entry.isFile() && entry.name.endsWith(".shade.typeshade.ts")) {
      const [header] = (await readFile(file, "utf8")).split(/\r?\n/, 1);
      if (!header.startsWith("// Generated by typeshade from "))
        throw new Error(
          `Refusing to clean a non-generated TypeShade view: ${file}`,
        );
      await unlink(file);
    }
  }
}

async function generatedShadeViews(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const file = resolve(directory, entry.name);
    if (entry.isDirectory()) found.push(...(await generatedShadeViews(file)));
    else if (entry.isFile() && entry.name.endsWith(".shade.typeshade.ts"))
      found.push(file);
  }
  return found;
}

try {
  const commit = git(["rev-parse", "HEAD"]);
  const worktreeFingerprint = await fingerprintWorktree();
  await mkdir(resolve(".typenn-build"), { recursive: true });
  const generated = await generateElementwiseOpIr();
  report = await (async () => {
    server = await createServer({
      configFile: resolve(".typenn-build/vite.config.mjs"),
      appType: "custom",
      server: { middlewareMode: true },
    });
    const verification = await server.ssrLoadModule(
      "/scripts/verify-elementwise-fusion.ts",
    );
    return verification.runElementwiseFusionVerification({
      commit,
      worktreeFingerprint,
    });
  })();
  if (report.helperFingerprint !== generated.fingerprint)
    throw new Error(
      "Verification suite fingerprint does not match generated helpers.",
    );
  const expectedIds = [
    "T01-source-provenance",
    "T02-source-change-production-path",
    "T03-helper-contract-negative-fixtures",
    "T04-generic-dag-composition",
    "T05-shared-diamond",
    "T06-repeated-leaf-dedup",
    "T07-one-entry-storage-contract",
    "T08-real-cpu-emission-path",
    "T09-f32-rounding-and-bounds",
    "T10-cache-topology-data-and-fingerprint",
    "T11-conservative-fallbacks",
    "T12-device-storage-limit-before-resources",
    "T13-distribution-entrypoint",
    "FI01-helper-provenance-mutation",
    "FI02-shared-local-clobber-mutation",
    "FI03-intermediate-storage-mutation",
    "FI04-real-codegen-fallback-mutation",
    "FI05-no-f32-rounding-mutation",
    "FI06-stale-helper-fingerprint-mutation",
    "FI07-device-cap-wiring-mutation",
    "FI08-stale-input-values-mutation",
  ];
  const actualIds = report.tests.map(({ id }) => id);
  if (JSON.stringify(actualIds) !== JSON.stringify(expectedIds))
    throw new Error(
      `Acceptance test IDs differ from the required set: ${actualIds.join(", ")}`,
    );
} catch (error) {
  report = {
    ...report,
    passed: false,
    runnerError:
      error instanceof Error ? (error.stack ?? error.message) : String(error),
  };
  process.exitCode = 1;
} finally {
  await server?.close();
  if (generatedBefore === undefined) await rm(generatedPath, { force: true });
  else await writeFile(generatedPath, generatedBefore);
  await removeGeneratedShadeViews("src");
  const generatedAfterCleanup = await readFile(generatedPath).catch(
    () => undefined,
  );
  const viewsAfterCleanup = await generatedShadeViews("src");
  const cleanupPassed =
    viewsAfterCleanup.length === 0 &&
    (generatedBefore === undefined
      ? generatedAfterCleanup === undefined
      : generatedAfterCleanup?.equals(generatedBefore));
  const t13Index = report.tests.findIndex(
    ({ id }) => id === "T13-distribution-entrypoint",
  );
  if (t13Index >= 0) {
    const t13 = report.tests[t13Index];
    report.tests[t13Index] = cleanupPassed
      ? {
          ...t13,
          assertions: [
            ...t13.assertions,
            "generated declaration and TypeShade source views are cleaned up",
          ],
        }
      : {
          ...t13,
          status: "failed",
          error: `Generated source cleanup failed: declaration=${generatedAfterCleanup ? "present" : "absent"}, views=${viewsAfterCleanup.join(", ")}`,
        };
  }
  report.passed = report.passed && cleanupPassed;
  await mkdir(resolve(".typenn-build"), { recursive: true });
  await writeFile(reportPath, `${JSON.stringify(report, null, 2)}\n`, "utf8");
  process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
  if (!report.passed) process.exitCode = 1;
}
