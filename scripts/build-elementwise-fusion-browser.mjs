import { build as bundle } from "esbuild";
import { build as viteBuild } from "vite";
import { readdir, readFile, rm, unlink } from "node:fs/promises";
import { generateElementwiseOpIr } from "./build-elementwise-op-ir.mjs";

const generatedShadeHeader =
  /^\/\/ Generated by typeshade from .+\.shade\.ts\. Do not edit; `tshc sync` rewrites it\./;

async function removeGeneratedShadeViews(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filePath = `${directory}/${entry.name}`;
    if (entry.isDirectory()) {
      await removeGeneratedShadeViews(filePath);
    } else if (entry.isFile() && entry.name.endsWith(".shade.typeshade.ts")) {
      const source = await readFile(filePath, "utf8");
      if (generatedShadeHeader.test(source)) await unlink(filePath);
    }
  }
}

const configSource = `
  import { defineConfig } from "vite";
  import { typeshade } from "typeshade/vite";

  export default defineConfig({
    plugins: [typeshade()],
    build: {
      target: "esnext",
      outDir: ".typenn-build/elementwise-fusion-browser",
      emptyOutDir: true,
      rollupOptions: {
        input: {
          graphIr: "scripts/verify-elementwise-fusion.html",
          publishedBundle: "scripts/verify-elementwise-fusion-production.html",
        },
      },
    },
  });
`;

await bundle({
  stdin: {
    contents: configSource,
    resolveDir: process.cwd(),
    sourcefile: "elementwise-fusion-browser.config.ts",
  },
  outfile: ".typenn-build/elementwise-fusion-browser.config.mjs",
  bundle: true,
  platform: "node",
  format: "esm",
  external: ["vite", "typescript"],
});

await removeGeneratedShadeViews("src");

try {
  await generateElementwiseOpIr();
  await viteBuild({
    configFile: ".typenn-build/elementwise-fusion-browser.config.mjs",
  });
} finally {
  await removeGeneratedShadeViews("src");
  await rm("src/runtime/elementwise-op-declarations.generated.ts", {
    force: true,
  });
  await rm(".typenn-build/generate-elementwise-op-ir.mjs", { force: true });
}
