import { mkdir, readdir, rm, unlink } from "node:fs/promises";
import { build as bundle } from "esbuild";
import { build as viteBuild } from "vite";
import { execFileSync } from "node:child_process";

const configDir = ".typenn-build";

async function removeGeneratedShadeViews(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) {
      await removeGeneratedShadeViews(path);
    } else if (entry.isFile() && entry.name.endsWith(".shade.typeshade.ts")) {
      await unlink(path);
    }
  }
}

// These executable CPU/manifest views are generated by the TypeShade Vite plugin.
// Clear stale views first so renamed or removed kernels cannot linger in the source tree.
await removeGeneratedShadeViews("src");
await mkdir(configDir, { recursive: true });

// TypeShade is currently distributed from TypeScript source. Bundle its build-time Vite
// compiler into a temporary config so Node can load it without shipping the compiler to users.
await bundle({
  entryPoints: ["vite.config.ts"],
  outfile: `${configDir}/vite.config.mjs`,
  bundle: true,
  platform: "node",
  format: "esm",
  external: ["vite", "typescript"],
});

try {
  await viteBuild({ configFile: `${configDir}/vite.config.mjs` });
  execFileSync("node_modules/.bin/tsc", ["-p", "tsconfig.json"], {
    stdio: "inherit",
  });
} finally {
  // Keep generated TypeShade views available to tsc, but out of the source tree afterward.
  await removeGeneratedShadeViews("src");
}
await rm("dist/types/kernels", { recursive: true, force: true });
